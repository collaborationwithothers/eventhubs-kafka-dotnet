def verify_expected(result):
    """The values the plan pins. A difference is a finding for Hari, not a fix."""
    pub = result["publication"]
    got = ["%s %s %s %s %s %s %s %s" % (c["label"], tod(c["I0"]), tod(c["before_service"]), tod(c["I1"]),
                                        tod(c["I2"]), tod(c["after_service"]), c["seconds_from_window_start"],
                                        c["seconds_before_cutoff"]) for c in pub["per_client"]]
    need(got == EXPECTED_CLIENTS, "EXPECTED", "the clients table differs from the pinned values")
    for kind in "PC":
        rows = [c for c in pub["per_client"] if c["label"][0] == kind]
        need([(c["initial_offset"], c["diagnostic_offset"]) for c in rows] == EXPECTED_OFFSETS[kind], "EXPECTED",
             "%s offsets differ" % kind)
        need(all(c["acquired_expiry_unchanged"] and c["acquired_expiry"] == [EXPECTED_ACQUIRED[kind]] * 3
                 for c in rows), "EXPECTED", "%s acquired expiry differs or changed" % kind)
        need([c["row_bytes"] for c in rows] == EXPECTED_ROW_BYTES[kind], "EXPECTED", "%s row bytes differ" % kind)
    need([c["row_bytes"] for c in pub["probe_context"]] == EXPECTED_ROW_BYTES["X"], "EXPECTED", "X row bytes differ")
    need(pub["row_bytes"] == EXPECTED_ROW_TOTALS, "EXPECTED", "row byte totals differ")
    need(pub["broker_counts"] == EXPECTED_BROKER, "EXPECTED", "broker counts differ")
    need((pub["teardown"]["ephemeral_state_empty"], pub["teardown"]["aks_stopped"]) == EXPECTED_TEARDOWN,
         "EXPECTED", "teardown times differ")


