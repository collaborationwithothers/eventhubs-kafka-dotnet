def load_inputs(cand_dir, pods_dir, batch_log, stop_log, c5_summary):
    inp = {}
    for kind, base in (("candidates", cand_dir), ("pods", pods_dir)):
        for dirpath, _dirs, files in os.walk(base):
            for name in files:
                full = os.path.join(dirpath, name)
                rel = os.path.relpath(full, base).replace(os.sep, "/")
                with open(full, "rb") as handle:
                    inp[(kind, rel)] = handle.read()
    for key, path in (("batch_log", batch_log), ("stop_log", stop_log), ("c5_summary", c5_summary)):
        with open(path, "rb") as handle:
            inp[key] = handle.read()
    return inp


def git(*args):
    return subprocess.check_output(("git", "-C", ROOT) + args, stderr=subprocess.STDOUT)


def git_ok(*args):
    return subprocess.call(("git", "-C", ROOT) + args, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL) == 0


def jload(data, check, name):
    try:
        return json.loads(data.decode("utf-8"))
    except (ValueError, UnicodeDecodeError):
        raise Gap(check, "%s is not valid JSON" % name)


def log_key(inp, job):
    keys = [k for k in inp if isinstance(k, tuple) and k[0] == "pods" and k[1].startswith(job + "/")
            and k[1].endswith(".log")]
    need(len(keys) == 1, "F2", "%s does not hold exactly one log file" % job)
    return keys[0]


def split_rows(data):
    """Returns (index, JSON text) for each row line of a log."""
    lines = data.decode("utf-8").split("\n")
    return [(i, line[len(MARKER):]) for i, line in enumerate(lines) if line.startswith(MARKER)]


