def check_f2(inp, ctx):
    """Rows."""
    rows = {}
    for kind, spec in ACTORS.items():
        found = split_rows(inp[log_key(inp, spec[0])])
        need(len(found) == 5, "F2", "%s log does not hold exactly five rows" % spec[0])
        parsed = {}
        for _i, text in found:
            size = len(text.encode("utf-8"))
            need(size <= ROW_LIMIT, "F2", "a %s row is %d bytes, over %d" % (spec[0], size, ROW_LIMIT))
            try:
                obj = json.loads(text)
            except ValueError:
                raise Gap("F2", "a %s row is not JSON" % spec[0])
            need(isinstance(obj, dict), "F2", "a %s row is not one JSON object" % spec[0])
            need(is_int(obj.get("repeat")) and obj["repeat"] not in parsed, "F2",
                 "%s repeat values repeat or are not integers" % spec[0])
            parsed[obj["repeat"]] = (obj, size)
        need(sorted(parsed) == [1, 2, 3, 4, 5], "F2", "%s repeat values are not exactly 1 to 5" % spec[0])
        rows[kind] = parsed
    ctx["rows"] = rows


