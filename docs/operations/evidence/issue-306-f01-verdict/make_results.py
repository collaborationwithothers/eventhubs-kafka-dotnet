def check_f6(inp, ctx):
    """Expiry."""
    for kind, n, row in each_row(inp, ctx, "PC"):
        name = "%s%d" % (kind, n)
        for event in row["lifecycle"]["events"]:
            if event["stage"] != "installation_succeeded":
                continue
            attempt = event["attempt"]
            acquired, cap_at = ticks(event["acquired_expires_on"]), ticks(event["cap_computed_at"])
            need(event["test_expiry_cap_milliseconds"] == CAP_MS, "F6", "%s attempt %d cap differs" % (name, attempt))
            need(acquired > cap_at, "F6", "%s attempt %d acquired expiry is not after the cap time" % (name, attempt))
            need(ticks(event["effective_expires_on"]) == min(acquired, cap_at + CAP_MS * 10 ** 4), "F6",
                 "%s attempt %d effective expiry differs from the capped value" % (name, attempt))
            need(event["installed_expires_on"] == event["effective_expires_on"], "F6",
                 "%s attempt %d installed expiry differs from the effective one" % (name, attempt))
            returned = ticks(evt(row, attempt, "acquisition_returned")["observed_at"])
            need(returned <= cap_at <= ticks(event["observed_at"]), "F6",
                 "%s attempt %d cap time is outside its acquisition and install times" % (name, attempt))
        need(evt(row, 1, "installation_succeeded")["installed_expires_on"] == row["initial_installed_expires_on"],
             "F6", "%s initial installed expiry differs" % name)


