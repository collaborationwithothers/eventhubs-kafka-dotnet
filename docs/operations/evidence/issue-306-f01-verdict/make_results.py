def run_checks(inp, ids=None, ctx=None):
    """Runs the checks in number order and stops at the first failure."""
    ctx = {} if ctx is None else ctx
    for check in (ids or CHECK_IDS):
        try:
            CHECKS[check](inp, ctx)
        except Gap:
            raise
        except (KeyError, TypeError, IndexError, AttributeError, ValueError, UnicodeDecodeError) as error:
            raise Gap(check, "malformed input (%s: %s)" % (type(error).__name__, error))
    return ctx


