def edit_row(inp, kind, repeat, fn):
    new = dict(inp)
    key = log_key(inp, ACTORS[kind][0])
    lines = inp[key].decode("utf-8").split("\n")
    for i, line in enumerate(lines):
        if line.startswith(MARKER):
            obj = json.loads(line[len(MARKER):])
            if obj["repeat"] == repeat:
                fn(obj)
                lines[i] = MARKER + json.dumps(obj)
                break
    else:
        raise AssertionError("row not found")
    new[key] = "\n".join(lines).encode("utf-8")
    return new


def edit_lines(inp, kind, fn):
    """Edits an actor log as text: fn gets the line list and returns the edited list."""
    new = dict(inp)
    key = log_key(inp, ACTORS[kind][0])
    new[key] = "\n".join(fn(inp[key].decode("utf-8").split("\n"))).encode("utf-8")
    return new


def edit_cand(inp, name, fn, rehash=True):
    new = dict(inp)
    obj = json.loads(inp[("candidates", name)])
    fn(obj)
    data = json.dumps(obj, indent=2).encode("utf-8")
    new[("candidates", name)] = data
    if rehash:
        rname = name.replace(".json", "-judge-completion.json")
        receipt = json.loads(inp[("candidates", rname)])
        receipt["candidate_sha256"] = sha256(data)
        new[("candidates", rname)] = json.dumps(receipt).encode("utf-8")
    return new


def edit_json(inp, key, fn):
    new = dict(inp)
    obj = json.loads(inp[key])
    fn(obj)
    new[key] = json.dumps(obj).encode("utf-8")
    return new


def set_ticks(row_event, field, delta, base):
    row_event[field] = ticks_to_text(base + delta)


def self_test(inp):
    cases = []

    def case(name, expect, mutate, ids=None, also=None):
        cases.append((name, expect, mutate, ids, also))

    def p1(fn):
        return lambda i: edit_row(i, "P", 1, fn)

    def c1(fn):
        return lambda i: edit_row(i, "C", 1, fn)

    # F1
    def add_extra(i):
        new = dict(i)
        new[("pods", "extra.json")] = b"{}"
        return new

    def append_lf(i):
        new = dict(i)
        new[("candidates", "F06-C6.json")] = i[("candidates", "F06-C6.json")] + b"\n"
        return new

    case("F1 extra pods file", "F1", add_extra, ["F1"])
    case("F1 candidate with LF appended", "F1", append_lf, ["F1"])

    # F2 cases edit the actor log text after re-serialization: padding appends ASCII spaces to the end of the
    # re-serialized JSON text of the row, before its LF, and the row is not parsed again before F2 runs; the
    # sixth-row case appends a copy of the re-serialized P1 line with repeat 6; the removal cases delete whole lines.
    def pad(target):
        def mutate(i):
            def fix(lines):
                at = [n for n, line in enumerate(lines) if line.startswith(MARKER)][0]
                base = MARKER + json.dumps(json.loads(lines[at][len(MARKER):]))
                lines[at] = base + " " * (target - len(base[len(MARKER):].encode("utf-8")))
                return lines
            return edit_lines(i, "P", fix)
        return mutate

    for size in (ROW_LIMIT - 1, ROW_LIMIT):
        case("F2 row of %d bytes passes" % size, None, pad(size))
    case("F2 row of %d bytes" % (ROW_LIMIT + 1), "F2", pad(ROW_LIMIT + 1))

    def sixth(i):
        def fix(lines):
            at = [n for n, line in enumerate(lines) if line.startswith(MARKER)]
            obj = json.loads(lines[at[0]][len(MARKER):])
            obj["repeat"] = 6
            lines.insert(at[-1] + 1, MARKER + json.dumps(obj))
            return lines
        return edit_lines(i, "P", fix)

    def drop_row(kind, repeat):
        def mutate(i):
            def fix(lines):
                keep = []
                for line in lines:
                    if line.startswith(MARKER) and json.loads(line[len(MARKER):])["repeat"] == repeat:
                        continue
                    keep.append(line)
                return keep
            return edit_lines(i, kind, fix)
        return mutate

    def drop_all(i):
        return edit_lines(i, "C", lambda lines: [line for line in lines if not line.startswith(MARKER)])

    case("F2 sixth row", "F2", sixth)
    case("F2 P2 with repeat 1", "F2", lambda i: edit_row(i, "P", 2, lambda r: r.update(repeat=1)))
    case("F2 P5 removed", "F2", drop_row("P", 5))
    case("F2 all C rows removed", "F2", drop_all)

    # F3 (predicate-to-test map, added by the plan check)
    case("F3 P1 client_id", "F3", p1(lambda r: r.update(client_id=r["pod_name"] + "-r2")))
    case("F3 P1 synthetic false", "F3", p1(lambda r: r.update(synthetic=False)))

    # F4
    case("F4 P1 trigger_attempt 2", "F4", p1(lambda r: r["handler_refresh"].update(trigger_attempt=2)))
    case("F4 P1 client_cleanup_completed false", "F4", p1(lambda r: r.update(client_cleanup_completed=False)))
    case("F4 P1 test_expiry_cap_ms 4999", "F4", p1(lambda r: r["handler_refresh"].update(test_expiry_cap_ms=4999)))

    # F5
    def drop_returned(r):
        r["lifecycle"]["events"].remove(evt(r, 2, "sdk_get_token_returned"))

    def same_stamp(r):
        evt(r, 2, "sdk_get_token_invoked")["timestamp"] = evt(r, 2, "callback_started")["timestamp"]

    case("F5 P1 attempt 2 returned removed", "F5", p1(drop_returned))
    case("F5 P1 attempt 2 equal timestamps", "F5", p1(same_stamp))
    case("F5 P1 unknown stage", "F5", p1(lambda r: evt(r, 2, "callback_started").update(stage="unknown_stage")))

    # F6
    def shift_i0(delta):
        def fn(r):
            e = evt(r, 1, "installation_succeeded")
            value = min(ticks(e["acquired_expires_on"]), ticks(e["cap_computed_at"]) + CAP_MS * 10 ** 4) + delta
            text = ticks_to_text(value)
            e["effective_expires_on"] = e["installed_expires_on"] = r["initial_installed_expires_on"] = text
        return fn

    for delta in (-1, 0, 1):
        case("F6 P1 I0 expiry %+d tick" % delta, None if delta == 0 else "F6", p1(shift_i0(delta)))

    def installed_plus_one(r):
        e = evt(r, 1, "installation_succeeded")
        text = ticks_to_text(ticks(e["effective_expires_on"]) + 1)
        e["installed_expires_on"] = r["initial_installed_expires_on"] = text

    case("F6 P1 I0 installed expiry +1 tick", "F6", p1(installed_plus_one))
    case("F6 P1 I2 acquired expiry equals cap time", "F6", p1(
        lambda r: evt(r, 3, "installation_succeeded").update(
            acquired_expires_on=evt(r, 3, "installation_succeeded")["cap_computed_at"])))

    # F7
    def after_at(extra):
        def fn(r):
            hr = r["handler_refresh"]
            hr["after_service"]["timestamp"] = hr["started_timestamp"] + WINDOW_S * FREQ + extra
        return fn

    case("F7 P1 service 1 ns before cutoff passes", None, p1(after_at(-1)))
    case("F7 P1 service at cutoff", "F7", p1(after_at(0)))
    case("F7 P1 service 1 ns after cutoff", "F7", p1(after_at(1)))
    case("F7 P1 admission at I2 timestamp", "F7", p1(
        lambda r: r["handler_refresh"].update(operation_admitted_timestamp=evt(r, 3, "installation_succeeded")["timestamp"])))

    # F8
    case("F8 P1 PossiblyPersisted", "F8", p1(lambda r: r["handler_refresh"]["after_service"].update(
        persistence_status="PossiblyPersisted")))
    case("F8 P1 equal offsets", "F8", p1(lambda r: r["handler_refresh"]["after_service"].update(
        offset=r["handler_refresh"]["before_service"]["offset"])))

    def both_partition_1(r):
        for label in ("before_service", "after_service"):
            r["handler_refresh"][label]["partition"] = 1

    case("F8 P1 partition 1", "F8", p1(both_partition_1))
    case("F8 P1 key present", "F8", p1(lambda r: r["handler_refresh"]["after_service"].update(key_base64="eA==")))

    # F9
    def both_value(r):
        for label in ("before_service", "after_service"):
            r["handler_refresh"][label]["value_base64"] = "eA=="

    case("F9 C1 value differs", "F9", c1(both_value))
    case("F9 C1 seek missing", "F9", c1(lambda r: r["handler_refresh"].update(seek_returned_timestamp=None)))
    case("F9 C1 seek at admission", "F9", c1(lambda r: r["handler_refresh"].update(
        seek_returned_timestamp=r["handler_refresh"]["operation_admitted_timestamp"])))

    # F10
    case("F10 X1 handler_refresh present", "F10", lambda i: edit_row(i, "X", 1, lambda r: r.update(handler_refresh={})))

    # F11
    def bad_receipt(i):
        new = dict(i)
        key = ("candidates", "F06-C9-judge-completion.json")
        receipt = json.loads(i[key])
        digest = receipt["candidate_sha256"]
        receipt["candidate_sha256"] = digest[:-1] + ("0" if digest[-1] != "0" else "1")
        new[key] = json.dumps(receipt).encode("utf-8")
        return new

    def seed_count_2(c):
        for client in c["repeats"][0]["clients"]:
            if client["client_id"].startswith(ACTORS["P"][0] + "-"):
                client["broker_count"] = 2

    case("F11 C9 receipt hash", "F11", bad_receipt)
    case("F11 C9 repeat 1 reasons", "F11", lambda i: edit_cand(i, "F06-C9.json",
                                                              lambda c: c["repeats"][0].update(reasons=["x"])))
    case("F11 C9 seed broker count conflict", "F11", lambda i: edit_cand(i, "F06-C9.json", seed_count_2))

    # F12
    case("F12 C9 judge collection incomplete", "F12", lambda i: edit_json(
        i, ("pods", JUDGE_JOBS[1] + "/collection-status.json"), lambda s: s.update(complete=False, gaps=["x"])))

    # F13 (line edits on the batch log bytes)
    def batch_lines(fn):
        def mutate(i):
            new = dict(i)
            new["batch_log"] = "\n".join(fn(i["batch_log"].decode("utf-8").split("\n"))).encode("utf-8")
            return new
        return mutate

    def is_empty_line(line):
        return line.rstrip().endswith("ephemeral_state_empty")

    def duplicate_empty(lines):
        at = [n for n, line in enumerate(lines) if is_empty_line(line)][0]
        return lines[:at + 1] + [lines[at]] + lines[at + 1:]

    case("F13 batch teardown line removed", "F13", batch_lines(lambda ls: [x for x in ls if not is_empty_line(x)]))
    case("F13 batch teardown line duplicated", "F13", batch_lines(duplicate_empty))

    # F14: after F2 to F13 pass on the unmodified rows
    def c5_edit(fn):
        return lambda i: edit_json(i, "c5_summary", fn)

    case("F14 unmodified inputs", None, lambda i: i, ["F14"])
    case("F14 break_passed false", "F14", c5_edit(lambda s: s.update(break_passed=False)), ["F14"])
    case("F14 commit set to the run source", "F14", c5_edit(lambda s: s.update(commit=SOURCE)), ["F14"])

    # Precedence
    def trigger_and_cutoff(r):
        r["handler_refresh"]["trigger_attempt"] = 2
        r["handler_refresh"]["after_service"]["timestamp"] = r["handler_refresh"]["started_timestamp"] + WINDOW_S * FREQ

    case("Precedence P1 trigger 2 and service at cutoff", "F4", p1(trigger_and_cutoff), None, "F7")

    failures = 0
    for name, expect, mutate, ids, also in cases:
        modified = mutate(inp)
        if ids is None:
            ids = ["F1"] if name.startswith("F1 ") else CHECK_IDS[1:13]
        got, extra = None, None
        try:
            run_checks(modified, ids)
        except Gap as gap:
            got = gap.check
        if also and got == expect:
            try:
                run_checks(modified, [also])
                extra = "%s did not also fail" % also
            except Gap:
                pass
        if got == expect and extra is None:
            print("PASS %s" % name)
        else:
            failures += 1
            print("FAIL %s: expected %s, got %s%s" % (name, expect, got, "; " + extra if extra else ""),
                  file=sys.stderr)
    return failures


