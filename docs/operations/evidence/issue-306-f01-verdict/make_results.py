class Gap(Exception):
    """A failed check. It is a gap in the evidence, never a contradiction or a zero."""

    def __init__(self, check, message):
        Exception.__init__(self, message)
        self.check = check
        self.message = message


def need(condition, check, message):
    if not condition:
        raise Gap(check, message)


def sha256(data):
    return hashlib.sha256(data).hexdigest()


def is_int(value):
    return isinstance(value, int) and not isinstance(value, bool)


