def main(argv):
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--candidates", required=True)
    parser.add_argument("--pods", required=True)
    parser.add_argument("--batch-log", required=True)
    parser.add_argument("--stop-log", required=True)
    parser.add_argument("--c5-summary", required=True)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--tables", action="store_true")
    parser.add_argument("--self-test", action="store_true")
    args = parser.parse_args(argv)
    inp = load_inputs(args.candidates, args.pods, args.batch_log, args.stop_log, args.c5_summary)
    try:
        if args.self_test:
            run_checks(inp, CHECK_IDS[:13])
            run_checks(inp, ["F14"])
            return 1 if self_test(inp) else 0
        result = build(inp)
        data = json_bytes(result)
        if args.tables:
            print("\n\n".join(render_tables(result)))
            return 0
        if args.check:
            with open(RESULT_JSON, "rb") as handle:
                need(handle.read() == data, "CHECK", "results/F01/2026-10-31.json differs from the generated bytes")
            with open(RESULT_MD, "r", encoding="utf-8") as handle:
                report = handle.read()
            for table in render_tables(result):
                need(table in report, "CHECK", "a generated table block is missing from results/F01/2026-10-31.md")
            return 0
        os.makedirs(os.path.dirname(RESULT_JSON), exist_ok=True)
        with open(RESULT_JSON, "wb") as handle:
            handle.write(data)
        return 0
    except Gap as gap:
        print("FAIL %s: %s" % (gap.check, gap.message), file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
