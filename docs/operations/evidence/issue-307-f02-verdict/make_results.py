def edit_capture(m, suffix, fn):
    key = log_key(m, suffix)
    lines = m["pods"][key].decode("utf-8").split("\n")
    i = next(i for i, l in enumerate(lines) if l.startswith(CAPTURE))
    obj = json.loads(lines[i][len(CAPTURE):])
    fn(obj)
    lines[i] = CAPTURE + json.dumps(obj, separators=(",", ":"))
    m["pods"][key] = "\n".join(lines).encode("utf-8")


def edit_log(m, suffix, fn):
    key = log_key(m, suffix)
    out = []
    for l in m["pods"][key].decode("utf-8").split("\n"):
        r = fn(l) if l.startswith(CLIENT_LOG) else l
        if r is not None:
            out.append(r)
    m["pods"][key] = "\n".join(out).encode("utf-8")


def edit_candidate(m, cfg, fn):
    name = "F06-%s.json" % cfg
    obj = json.loads(m["cand"][name].decode("utf-8"))
    fn(obj)
    m["cand"][name] = (json.dumps(obj, indent=2) + "\n").encode("utf-8")
    rec_name = "F06-%s-judge-completion.json" % cfg
    rec = json.loads(m["cand"][rec_name].decode("utf-8"))
    rec["candidate_sha256"] = sha256(m["cand"][name])
