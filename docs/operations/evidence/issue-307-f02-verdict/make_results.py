def edit_json(m, where, name, fn):
    obj = json.loads(m[where][name].decode("utf-8"))
    fn(obj)
    m[where][name] = (json.dumps(obj, indent=2) + "\n").encode("utf-8")


def slot_after(m, stage, repeat):
    ctx = {}
