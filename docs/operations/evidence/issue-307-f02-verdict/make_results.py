def read_tree(directory):
    base = pathlib.Path(directory)
    out = {}
    for path in sorted(base.rglob("*")):
        if path.is_file():
            out[path.relative_to(base).as_posix()] = path.read_bytes()
    return out


def load_inputs(args):
    def one(path):
        need("G1", pathlib.Path(path).is_file(), "missing input " + str(path))
        return pathlib.Path(path).read_bytes()
    need("G1", pathlib.Path(args.candidates).is_dir() and pathlib.Path(args.pods).is_dir(), "missing input directory")
    return {"cand": read_tree(args.candidates), "pods": read_tree(args.pods), "batch": one(args.batch_log),
            "stop": one(args.stop_log), "c5": one(args.c5_summary)}


