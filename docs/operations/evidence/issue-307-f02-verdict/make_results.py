def slot_lines(text, stage, repeat, rep):
    marker = " stage=%s repeat=%d " % (stage, repeat)
    log = [l for l in text.split("\n") if l.startswith(CLIENT_LOG) and marker in l]
    lines = list(log)
    lines += [e.get("reason") or "" for e in rep.get("client_errors", [])]
    if rep.get("error") is not None:
        lines.append(rep["error"].get("reason") or "")
    return log, lines


def eval_slot(stage, rep, text, log_bytes):
    log, lines = slot_lines(text, stage, rep["repeat"], rep)
    diagnostics = list(rep.get("diagnostics") or [])
    delivery = rep.get("delivery")
    error = rep.get("error")
    ev = {c: 0 for c in CLASSES}
    if delivery is not None and delivery.get("persistence_status") == "Persisted" and delivery.get("error") is None:
        ev["2.1"] = 1
    if error is not None and error.get("code") == 29 and error.get("origin") == "broker" and delivery is None:
        ev["2.2"] = 1
    ev["2.3"] = sum("SASL OAUTHBEARER authentication successful" in l for l in lines)
    if ev["2.3"] == 0:
        ev["2.4"] = sum("SASL OAUTHBEARER authentication failed (principal=" in l for l in lines)
        for l in lines:
            if "SASL authentication error: " in l:
                after = l.split("SASL authentication error: ", 1)[1]
                if not after.startswith("SaslAuthenticateRequest failed:") and not after.startswith("SaslAuthenticateResponse parsing failed:"):
                    ev["2.4"] += 1
    ev["2.5"] = sum("Waking up waiting broker threads after setting OAUTHBEARER token" in l for l in lines)
    t26 = [l for l in lines if "Failed to retrieve JWT token from" in l or "Failed to retrieve OIDC token from" in l]
    ev["2.6"] = len(t26)
    ev["2.7"] = sum("Failed to acquire SASL OAUTHBEARER token:" in l or "Failed to append params" in l for l in lines)
    ev["2.8"] = sum(d.startswith("construction:") for d in diagnostics) + (1 if error is not None and error.get("origin") == "construction" else 0)
    cls = next((c for c in CLASSES if ev[c] > 0), "2.9")
    lower = "capture_limit" in diagnostics or log_bytes >= LOG_LIMIT
    incomplete = cls == "2.9" or "not_attempted_cleanup" in diagnostics
    answers = []
    for l in t26:
        mm = TOKEN_ANSWER.search(l)
        need("G6", mm is not None, "a token-endpoint line does not match the answer pattern")
        answers.append((int(mm.group(2)), mm.group(1)))
    aadsts = sorted(set(re.findall(r"AADSTS(\d+)", " ".join(body for _s, body in answers))))
    principals = {"workload": 0, "other": 0, "empty": 0}
    success_principals = []
    for l in lines:
        if "SASL OAUTHBEARER authentication successful" in l or "SASL OAUTHBEARER authentication failed (principal=" in l:
            for p in PRINCIPAL.findall(l):
                principals[p] += 1
                if "SASL OAUTHBEARER authentication successful" in l:
                    success_principals.append(p)
    trust_lines = sum("error adding trust anchors" in l for l in lines)
    trust_in_2_6 = sum("error adding trust anchors" in l for l in t26)
    construction_ioe = sum(d == "construction:InvalidOperationException" for d in diagnostics)
    return {
        "stage": stage, "repeat": rep["repeat"], "client_id": rep["client_id"], "class": cls,
        "lower_bound": lower, "incomplete": incomplete, "lines_for_class": ev.get(cls, 0),
        "other_classes": [(c, ev[c]) for c in CLASSES if ev[c] > 0 and c != cls],
        "client_log_lines": len(log), "principals": principals, "success_principals": success_principals,
        "http_statuses": sorted({s for s, _b in answers}), "answers": answers, "aadsts": aadsts,
        "first_token_endpoint_body": answers[0][1] if answers else None,
        "error": None if error is None else {"code": error.get("code"), "origin": error.get("origin"), "reason": error.get("reason")},
        "diagnostics": diagnostics, "elapsed_ms": rep.get("elapsed_ms"), "terminal": rep.get("terminal"),
        "trust_anchor_lines": trust_lines, "rule7": trust_in_2_6 > 0 or construction_ioe > 0,
    }


