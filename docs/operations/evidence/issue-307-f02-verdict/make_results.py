def hyp_decisions(slot):
    cls = slot["class"]
    principals = slot["principals"]
    n_pr = sum(principals.values())
    only_other = n_pr > 0 and principals["other"] == n_pr
    ok_answers = bool(slot["answers"]) and all(s >= 400 for s, _b in slot["answers"])
    out = {}
    # H-imds-workload (nativeimds, line 1)
    if "workload" in slot["success_principals"]:
        out["H-imds-workload"] = "contradicts"
    elif (cls == "2.6" and ok_answers and all(b != "" for _s, b in slot["answers"])) or only_other:
        out["H-imds-workload"] = "supports"
    else:
        out["H-imds-workload"] = "undecided"
    # H-imds-default (nativeimdsnode, line 2)
    if cls == "2.1" or "workload" in slot["success_principals"]:
        out["H-imds-default"] = "contradicts"
    elif (cls == "2.2" and only_other) or (cls == "2.6" and any(
            s >= 400 and "Multiple user assigned identities exist" in b for s, b in slot["answers"])):
        out["H-imds-default"] = "supports"
    else:
        out["H-imds-default"] = "undecided"
    # H-jwt and H-ca (nativejwt, rules 7 and 8)
    if slot["rule7"]:
        out["H-jwt"] = "undecided"
        out["H-ca"] = "contradicts"
    else:
        if cls in ("2.1", "2.2", "2.3", "2.4", "2.5"):
            out["H-jwt"] = "contradicts"
        elif cls == "2.6" and ok_answers and slot["aadsts"] and (not slot["lower_bound"] or LOWER_BOUND_DECIDES_H_JWT):
            out["H-jwt"] = "supports"
        else:
            out["H-jwt"] = "undecided"
        if H_CA_SUPPORT and slot["trust_anchor_lines"] == 0 and slot["answers"]:
            out["H-ca"] = "supports"
        else:
            out["H-ca"] = "undecided"
    return out


