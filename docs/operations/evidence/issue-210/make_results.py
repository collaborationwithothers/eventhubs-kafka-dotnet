def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def fail(message):
    sys.exit("make_results: " + message)


def load(directory, name):
    path = directory / name
    if sha256(path) != PINNED[name]:
        fail(name + " does not match its pinned SHA-256")
    return json.loads(path.read_bytes())


def check_candidate(item, configuration, candidate, receipt):
    expected = {
        "schema_version": 1, "mode": "single-action", "synthetic": True, "run_id": RUN_ID,
        "scenario_id": item, "configuration_id": configuration, "source_commit": SOURCE,
        "status": "complete_valid", "deterministic": True, "adr012_counts": "not_applicable",
        "diagnostics": [], "security_finding": False,
    }
    for key, value in expected.items():
        if candidate[key] != value:
            fail(f"{item} {configuration} {key} is {candidate[key]!r}")
    if [r["repeat"] for r in candidate["repeats"]] != [1, 2, 3, 4, 5]:
        fail(f"{item} {configuration} repeats are not 1 to 5")
    for r in candidate["repeats"]:
        if r["status"] != "complete_valid" or r["reasons"] != [] or r["outcome_class"] != candidate["outcome_class"]:
            fail(f"{item} {configuration} repeat {r['repeat']} differs")
        if not isinstance(r["broker_count"], int) or r["statistics_reference"] is None:
            fail(f"{item} {configuration} repeat {r['repeat']} has no broker count")
    job = f"{RUN_ID}-{item.lower()}-{configuration.lower()}-single-judge"
    receipt_expected = {
        "schema_version": 1, "mode": "single-action-judge", "run_id": RUN_ID, "scenario_id": item,
        "configuration_id": configuration, "source_commit": SOURCE, "job_name": job,
        "candidate_name": f"{RUN_ID}/single-action/{item}/{configuration}/candidate.json",
        "handler_exit_code": 0, "cleanup_completed": True,
    }
    for key, value in receipt_expected.items():
        if receipt[key] != value:
            fail(f"{item} {configuration} judge receipt {key} is {receipt[key]!r}")


def pod_evidence(pods, item, configuration, account):
    result = {}
    for suffix, expected_account in (("single", account), ("single-judge", "verifier")):
        job = f"{RUN_ID}-{item.lower()}-{configuration.lower()}-{suffix}"
        directory = pods / job
        status = json.loads((directory / "collection-status.json").read_bytes())
        if status != {"complete": True, "smoke_marker_valid": False, "gaps": []}:
            fail(job + " collection is not complete")
        document = json.loads((directory / "pods.json").read_bytes())
        items = document["items"]
        if len(items) != 1:
            fail(job + " does not have exactly one pod")
        pod = items[0]
        if pod["spec"]["serviceAccountName"] != expected_account or pod["status"]["phase"] != "Succeeded":
            fail(job + " has the wrong account or phase")
        containers = pod["status"]["containerStatuses"]
        if len(containers) != 1:
            fail(job + " does not have exactly one container")
        terminated = containers[0]["state"]["terminated"]
        if terminated["exitCode"] != 0:
            fail(job + " container did not exit 0")
        logs = sorted(p.name for p in directory.glob("*.log"))
        if len(logs) != 1:
            fail(job + " does not have exactly one log")
        result["capture" if suffix == "single" else "judge"] = {
            "job": job,
            "pod": pod["metadata"]["name"],
            "service_account": expected_account,
            "container_started_at": terminated["startedAt"],
            "container_finished_at": terminated["finishedAt"],
            "exit_code": 0,
            "pod_log_member": f"{job}/{logs[0]}",
            "pod_json_member": f"{job}/pods.json",
        }
    return result


def check_logs(pods):
    """Checks the pod-log statements the reports make.

    B01 C1 must log, per repeat 1 to 5, the stated number of librdkafka FAIL lines
    reporting a connection reset by the broker. Every other capture log in scope
    must contain no librdkafka log line, which starts with '%'.
    """
    expected_resets = [11, 10, 9, 11, 10]
    for item, spec in ITEMS.items():
        for configuration in spec["configurations"]:
            job = f"{RUN_ID}-{item.lower()}-{configuration.lower()}-single"
            (log,) = (pods / job).glob("*.log")
            native = [line for line in log.read_text(errors="replace").splitlines() if line.startswith("%")]
            if (item, configuration) == ("B01", "C1"):
                counts = [sum(1 for line in native if f"-r{n}#producer-" in line and "|FAIL|" in line and "reset by peer" in line)
                          for n in range(1, 6)]
                if counts != expected_resets or not all("reset by peer" in line or "Connection reset by peer" in line for line in native):
                    fail(f"B01 C1 reset lines are {counts}")
            elif native:
                fail(f"{job} has {len(native)} librdkafka log lines")


def classes(candidates):
    return {c: candidates[c]["outcome_class"] for c in candidates}


def succeeds(oc):
    return oc["result"] == "success"


def errors(oc, origin=None):
    return oc["result"] == "error" and (origin is None or oc["origin"] == origin)


def derive(item, oc):
    for value in oc.values():
        if value["result"] == "error" and value["origin"] == "construction":
            fail(item + " has a construction-origin outcome")
    if item == "B01":
        if not succeeds(oc["C0"]):
            fail("B01 control failed")
        h = {"H0": "holds", "H1": "holds" if errors(oc["C1"]) else "contradicted"}
        verdict = "confirmed" if h["H1"] == "holds" else "contradicted"
    elif item == "B03":
        if not succeeds(oc["C1"]):
            fail("B03 control failed")
        h = {"H0": "holds"}
        for name, configuration in (("H1_snappy", "C2"), ("H1_lz4", "C3"), ("H1_zstd", "C4")):
            h[name] = "holds" if errors(oc[configuration]) else "contradicted"
        verdict = "confirmed" if all(v == "holds" for v in h.values()) else "contradicted"
    elif item == "B05":
        returned = succeeds(oc["C1"])
        h = {"H1": "holds" if returned else "contradicted", "H2": "contradicted" if returned else "holds"}
        verdict = "confirmed"
    elif item == "C12":
        if errors(oc["C1"], "broker") or succeeds(oc["C2"]):
            verdict = "contradicted"
        elif succeeds(oc["C1"]) and errors(oc["C2"], "broker"):
            verdict = "confirmed"
        else:
            verdict = "untestable"
        h = {"H1": "holds" if succeeds(oc["C1"]) else "contradicted",
             "H2": "holds" if errors(oc["C2"], "broker") else "contradicted"}
    return {"verdict": verdict, "hypotheses": h, "reason": None}


def build(item, candidates_dir, pods_dir):
    spec = ITEMS[item]
    candidates, receipts, evidence = {}, {}, {}
    for configuration in spec["configurations"]:
        candidate = load(candidates_dir, f"{item}-{configuration}.json")
        receipt = load(candidates_dir, f"{item}-{configuration}-judge-completion.json")
        check_candidate(item, configuration, candidate, receipt)
        evidence[configuration] = pod_evidence(pods_dir, item, configuration, spec["capture_account"])
        if receipt["pod_name"] != evidence[configuration]["judge"]["pod"]:
            fail(f"{item} {configuration} judge receipt names another pod")
        candidates[configuration] = candidate
        receipts[configuration] = receipt
    last = spec["configurations"][-1]
    for configuration in spec["configurations"][:-1]:
        if candidates[configuration]["item_assessment"] is not None:
            fail(f"{item} {configuration} carries an item assessment")
    derived = derive(item, classes(candidates))
    if derived != candidates[last]["item_assessment"]:
        fail(f"{item} derived {derived} differs from the verifier's {candidates[last]['item_assessment']}")
    digests = {json.dumps(c["image_digests"], sort_keys=True) for c in candidates.values()}
    versions = {(c["managed_version"], c["native_version"]) for c in candidates.values()}
    if len(digests) != 1 or len(versions) != 1:
        fail(item + " configurations differ in images or versions")
    managed, native = versions.pop()
    codes = sorted({c["outcome_class"]["error_code"] for c in candidates.values() if c["outcome_class"]["error_code"] is not None})
    publication = {
        "item": item,
        "proposed_verdict": derived["verdict"],
        "summary": SUMMARIES[item],
        "hypotheses": derived["hypotheses"],
        "derivation": "re-derived from scenarios/" + item + "/expected.yaml decision rules by make_results.py; equal to the verifier item_assessment",
        "per_configuration": {
            c: {
                "status": candidates[c]["status"],
                "deterministic": candidates[c]["deterministic"],
                "outcome_class": candidates[c]["outcome_class"],
                "broker_count_per_repeat": [r["broker_count"] for r in candidates[c]["repeats"]],
                "broker_count_lower_bound": True,
            }
            for c in spec["configurations"]
        },
        "error_code_names": {str(code): ERROR_NAMES[code] for code in codes},
        "adr012_counts": "not_applicable",
        "run": {
            "workflow_run": RUN,
            "attempt": 1,
            "run_id": RUN_ID,
            "source_commit": SOURCE,
            "candidate_artifact": CANDIDATE_ARTIFACT,
            "pod_artifact": POD_ARTIFACT,
            "jobs": evidence,
        },
        "versions": {
            "confluent_kafka_managed": managed,
            "librdkafka_native": native,
            "image_digests": candidates[last]["image_digests"],
        },
        "environment": {
            "region": "uksouth",
            "event_hubs_sku": "Premium",
            "pu_count": 1,
            "node_size": "Standard_D4ds_v5",
            "node_size_evidence": "inferred_from_pinned_configuration_and_no_change_cluster_plan",
            "sources": [
                RUN + "/job/121897291309",
                REPO + "/blob/" + SOURCE + "/infra/cluster/aks.tf",
            ],
        },
        "mutation_gate": {
            "run": REPO + "/actions/runs/40415248275",
            "summary_artifact": REPO + "/actions/runs/40415248275/artifacts/12705444729",
            "commit": SOURCE,
            "measurement_complete": True,
            "break_passed": True,
            "numerator": 1302,
            "denominator": 1302,
        },
        "workload": "synthetic",
    }
    return {
        "publication": publication,
        "candidates": candidates,
        "judge_receipts": receipts,
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--candidates", required=True, type=pathlib.Path)
    parser.add_argument("--pods", required=True, type=pathlib.Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    check_logs(args.pods)
    mismatched = []
    for item in ITEMS:
        text = json.dumps(build(item, args.candidates, args.pods), indent=2) + "\n"
        target = pathlib.Path("results") / item / (DATE + ".json")
        if args.check:
            if not target.exists() or target.read_text() != text:
                mismatched.append(str(target))
        else:
            target.write_text(text)
        print(item, hashlib.sha256(text.encode()).hexdigest())
    if mismatched:
        fail("generated output differs from " + ", ".join(mismatched))


if __name__ == "__main__":
    main()
